# Comparison operators
# Less than: <    Greater than: >
# Less than or equal to: <=   Greater than or equal to: >=
# Is equal to: ==   Is not equal to: !=
25 < 50    # TRUE
25 > 50    # FALSE
25 <= 50   # TRUE
25 >= 50   # FALSE
25 == 50   # FALSE
25 != 50   # TRUE
